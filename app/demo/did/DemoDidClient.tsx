function resolutionOriginStatic(): string {
  const fromEnv = process.env.NEXT_PUBLIC_DID_RESOLUTION_ORIGIN?.trim();
  if (fromEnv) {
    return fromEnv.replace(/\/$/, "");
  }
  return "https://tabulas.eu";
}

function useResolutionOrigin(): string {
  const [origin, setOrigin] = useState(resolutionOriginStatic);
  useEffect(() => {
    if (!process.env.NEXT_PUBLIC_DID_RESOLUTION_ORIGIN?.trim()) {
      // Client-only: rewrite tabulas.eu URLs to the actual host (see docs).
      // eslint-disable-next-line react-hooks/set-state-in-effect -- sync browser origin once after mount
      setOrigin(window.location.origin);
    }
  }, []);
  return origin;
}

