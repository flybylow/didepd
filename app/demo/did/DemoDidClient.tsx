function verifyStampLabel(stamp: CredentialVerifyStamp | undefined): string {
  switch (stamp) {
    case "ok":
      return "Verified";
    case "fail":
      return "Failed";
    case "running":
      return "Checking…";
    default:
      return "Not checked";
  }
}

function verifyStampChipClass(stamp: CredentialVerifyStamp | undefined): string {
  const base =
    "inline-flex min-w-[5.75rem] max-w-[9rem] flex-col rounded-lg border px-2.5 py-1.5 text-left transition-colors sm:min-w-[6.5rem] sm:max-w-none";
  switch (stamp) {
    case "ok":
      return `${base} border-emerald-300 bg-emerald-50 text-emerald-900 dark:border-emerald-700 dark:bg-emerald-950/50 dark:text-emerald-100`;
    case "fail":
      return `${base} border-red-300 bg-red-50 text-red-900 dark:border-red-800 dark:bg-red-950/40 dark:text-red-100`;
    case "running":
      return `${base} border-amber-300 bg-amber-50 text-amber-950 dark:border-amber-700 dark:bg-amber-950/30 dark:text-amber-100`;
    default:
      return `${base} border-zinc-200 bg-white text-zinc-600 hover:bg-zinc-50 dark:border-zinc-600 dark:bg-zinc-900 dark:text-zinc-300 dark:hover:bg-zinc-800/80`;
  }
}

function verifyStampGlyph(stamp: CredentialVerifyStamp | undefined): string {
  switch (stamp) {
    case "ok":
      return "✓";
    case "fail":
      return "✗";
    case "running":
      return "…";
    default:
      return "○";
  }
}

