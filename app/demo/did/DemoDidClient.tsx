function resolutionBaseAtRuntime(originState: string): string {
  const env = process.env.NEXT_PUBLIC_DID_RESOLUTION_ORIGIN?.trim();
  if (env) {
    return env.replace(/\/$/, "");
  }
  if (typeof window !== "undefined") {
    return window.location.origin;
  }
  return originState.replace(/\/$/, "");
}

